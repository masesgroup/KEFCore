#!/usr/bin/env python3
"""
Generates/updates human-facing performance documentation from the JSON Lines files produced by
ProgramConfig.ReportResult (same input as analyze_results.py):

- Injects a condensed "at a glance" performance table into README.md and src/documentation/index.md,
  between marker comments (creating the markers on first run, replacing only what's between them on
  every later run — the rest of each file is left untouched).
- Writes a full, dedicated performance article page (default: src/documentation/articles/benchmarks.md)
  with the same condensed table plus the full per-test breakdown, reusing analyze_results.build_report
  for that detailed section so the two tools never drift apart on methodology/wording.

This script is meant to be run in CI (see .github/workflows/performance-docs.yaml), which then opens
a pull request with whatever changed — it does not commit or push anything itself.

Usage:
    python generate_perf_docs.py --input results/*.jsonl \
        --readme README.md \
        --doc-index src/documentation/index.md \
        --article src/documentation/articles/benchmarks.md \
        --run-url https://github.com/masesgroup/KEFCore/actions/runs/12345

No third-party dependencies; standard library only. Imports analyze_results.py from the same directory.
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from analyze_results import Record, load_records, summarize, build_report, HEADLINE_PATTERN, fmt_ms  # noqa: E402

MARKER_START = "<!-- PERFORMANCE-SUMMARY:START (auto-generated by generate_perf_docs.py, do not edit by hand) -->"
MARKER_END = "<!-- PERFORMANCE-SUMMARY:END -->"

# Anchor used only on the very first run, to decide where to insert the markers if they don't exist
# yet in a target file. Chosen because it's present, verbatim, in both README.md and
# src/documentation/index.md today. If it's ever renamed, later runs are unaffected (the markers,
# once inserted once, are what every subsequent run looks for) — only a fresh bootstrap would need
# updating.
BOOTSTRAP_ANCHOR = "### Project disclaimer"


def condensed_table_md(records: list[Record]) -> str:
    """The same 'Headline' grouping as analyze_results.py, rendered as a compact standalone table."""
    groups: dict[tuple[str, str, bool], list[Record]] = defaultdict(list)
    for r in records:
        if HEADLINE_PATTERN in r.testId.lower():
            groups[(r.project, r.framework, r.cache_enabled)].append(r)

    lines = []
    if not groups:
        lines.append("_No headline-pattern test found in the input; performance summary unavailable._")
        return "\n".join(lines)

    lines.append("| Project | Framework | Cache | Median iteration time (ms) |")
    lines.append("|---|---|---|---|")
    for (project, framework, cached), group_records in sorted(groups.items(), key=lambda kv: kv[0]):
        s = summarize(group_records)
        cache_label = "cached" if cached else "non-cached"
        short_project = project.rsplit(".", 1)[-1]  # e.g. "MASES...Test.Benchmark" -> "Benchmark"
        lines.append(f"| {short_project} | {framework} | {cache_label} | {fmt_ms(s.median_ms)} |")
    return "\n".join(lines)


def readme_block_md(records: list[Record]) -> str:
    """condensed_table_md wrapped with a heading and a link to the full article, for injection into
    README.md/index.md — context that's useful whether the numbers are real or (as in this repo's own
    example) synthetic."""
    lines = ["### Performance", ""]
    lines.append(condensed_table_md(records))
    lines.append("")
    lines.append("Full breakdown: [performance benchmarks](src/documentation/articles/benchmarks.md).")
    return "\n".join(lines)


def inject_between_markers(path: Path, new_content: str, bootstrap_anchor: str) -> bool:
    """Returns True if the file was changed."""
    original = path.read_text(encoding="utf-8")
    block = f"{MARKER_START}\n{new_content}\n{MARKER_END}"

    if MARKER_START in original and MARKER_END in original:
        start = original.index(MARKER_START)
        end = original.index(MARKER_END) + len(MARKER_END)
        updated = original[:start] + block + original[end:]
    elif bootstrap_anchor in original:
        # First run: insert the block right before the anchor, with a blank line on each side.
        idx = original.index(bootstrap_anchor)
        updated = original[:idx] + block + "\n\n" + original[idx:]
    else:
        print(f"warning: neither markers nor bootstrap anchor found in {path}; leaving it untouched.", file=sys.stderr)
        return False

    if updated == original:
        return False
    path.write_text(updated, encoding="utf-8")
    return True


def build_article(records: list[Record], run_url: str | None) -> str:
    lines = []
    lines.append("---")
    lines.append("title: KEFCore performance benchmarks")
    lines.append("_description: Latest automated performance benchmark results for the Entity Framework Core provider for Apache Kafka™")
    lines.append("---")
    lines.append("")
    lines.append("# KEFCore: performance benchmarks")
    lines.append("")
    lines.append(f"> [!NOTE]\n> This page is auto-generated by `test/analyze-test-results/generate_perf_docs.py` "
                  f"from the latest scheduled CI benchmark run. Do not edit it by hand — changes will be "
                  f"overwritten on the next run. See [Performance tips](performancetips.md) for configuration "
                  f"guidance instead.")
    lines.append("")
    lines.append(f"Generated: {datetime.now(timezone.utc).isoformat()}")
    if run_url:
        lines.append(f"  \nSource run: [{run_url}]({run_url})")
    lines.append("")
    lines.append("## At a glance")
    lines.append("")
    lines.append(condensed_table_md(records))
    lines.append("")
    lines.append("## Full breakdown")
    lines.append("")
    lines.append("The complete per-test results, produced by "
                  "[`analyze_results.py`](https://github.com/masesgroup/KEFCore/tree/master/test/analyze-test-results):")
    lines.append("")
    # Reuse build_report's detailed sections (Failures / Summary by test / cached-vs-non-cached delta /
    # cross-framework comparison). Skip everything before "## Failures": build_report's own title,
    # "Generated"/"Total records analyzed" preamble, and its "## Headline" section are all redundant
    # here (this page already has its own title/timestamp above, and its own "At a glance" table).
    # Anchored on the section heading text rather than a hardcoded line count, so it keeps working if
    # analyze_results.py's preamble format changes.
    full_report = build_report(records, title="(embedded)")
    anchor = "## Failures"
    if anchor in full_report:
        lines.append(full_report[full_report.index(anchor):])
    else:
        lines.append(full_report)  # fallback: anchor not found, include everything rather than nothing
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--input", nargs="+", required=True, help="One or more JSON Lines files (as produced by ReportResult)")
    parser.add_argument("--readme", default=None, help="Path to README.md to update (skipped if not given)")
    parser.add_argument("--doc-index", default=None, help="Path to src/documentation/index.md to update (skipped if not given)")
    parser.add_argument("--article", default=None, help="Path to write the full benchmarks article page to (skipped if not given)")
    parser.add_argument("--run-url", default=None, help="Optional URL of the CI run this data came from, linked from the article page")
    args = parser.parse_args()

    paths = [Path(p) for p in args.input]
    missing = [p for p in paths if not p.exists()]
    if missing:
        print(f"error: input file(s) not found: {', '.join(str(p) for p in missing)}", file=sys.stderr)
        return 1

    records = load_records(paths)
    if not records:
        print("error: no records loaded from the given input; refusing to overwrite documentation with an empty summary.", file=sys.stderr)
        return 1

    table = readme_block_md(records)
    changed_any = False

    for label, target in (("README", args.readme), ("documentation index", args.doc_index)):
        if not target:
            continue
        path = Path(target)
        if not path.exists():
            print(f"error: {label} file not found: {path}", file=sys.stderr)
            return 1
        if inject_between_markers(path, table, BOOTSTRAP_ANCHOR):
            print(f"Updated {path}")
            changed_any = True
        else:
            print(f"{path} already up to date (or anchor/markers not found - see warning above, if any)")

    if args.article:
        article_path = Path(args.article)
        article_path.parent.mkdir(parents=True, exist_ok=True)
        new_article = build_article(records, args.run_url)
        old_article = article_path.read_text(encoding="utf-8") if article_path.exists() else None
        if new_article != old_article:
            article_path.write_text(new_article, encoding="utf-8")
            print(f"Updated {article_path}")
            changed_any = True
        else:
            print(f"{article_path} already up to date")

    print("Changes made." if changed_any else "No changes were necessary.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
